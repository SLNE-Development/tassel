/** The shape every language has to fill: the German dictionary with its literal texts widened to `string`. */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => unknown
    ? (...args: A) => string
    : { readonly [K in keyof T]: Widen<T[K]> };

